/**
 * Owns the Neon connection. The main thread blocks on a shared flag; this
 * thread is the only place that talks to Postgres.
 *
 * Neon’s pooler drops session state between transactions, so every statement
 * is schema-qualified by the caller. `channel_binding` is a libpq option that
 * node-postgres does not implement, so it is stripped before connecting.
 */
const { parentPort } = require("node:worker_threads");
const { Pool, types } = require("pg");

// BIGINT comes back as a string by default. Timestamps are stored as epoch ms
// and the rest of the app treats them as numbers.
types.setTypeParser(20, (value) => (value === null ? null : Number(value)));

function connectionString() {
  const raw = process.env.DATABASE_URL;
  if (!raw) throw new Error("DATABASE_URL is not set");
  const url = new URL(raw);
  url.searchParams.delete("channel_binding");
  // `pg` treats sslmode=require as verify-full and warns about the alias.
  // Ask for the strict mode by name so the warning stays quiet.
  if (url.searchParams.get("sslmode") === "require") {
    url.searchParams.set("sslmode", "verify-full");
  }
  return url.toString();
}

function scrub(message) {
  return String(message).replace(/postgres(?:ql)?:\/\/[^@\s]+@/gi, "postgresql://***@");
}

const pool = new Pool({
  connectionString: connectionString(),
  max: 4,
  ssl: { rejectUnauthorized: true },
  idleTimeoutMillis: 20_000,
  connectionTimeoutMillis: 20_000,
});

pool.on("error", (err) => {
  console.error("[praxis] idle postgres client:", scrub(err.message));
});

