let ready = null;

function ensure() {
  if (!ready) {
    ready = bootstrap().catch((err) => {
      ready = null;
      throw err;
    });
  }
  return ready;
}

async function bootstrap() {
  const client = await pool.connect();
  try {
    for (const stmt of SCHEMA) await client.query(stmt);
  } finally {
    client.release();
  }
}

parentPort.on("message", async (msg) => {
  try {
    await ensure();
    const result = await pool.query(msg.sql, msg.params ?? []);
    msg.port.postMessage({ rows: result.rows, rowCount: result.rowCount ?? 0 });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    msg.port.postMessage({ error: scrub(message) });
  } finally {
    Atomics.store(msg.signal, 0, 1);
    Atomics.notify(msg.signal, 0, 1);
  }
});
